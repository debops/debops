"""Tests for ``debops.ansibleconfig``."""

import configparser
import os

import pytest

from debops.ansibleconfig import AnsibleConfig

PLUGIN_OPTIONS = ("library", "action_plugins", "callback_plugins",
                  "connection_plugins", "filter_plugins", "lookup_plugins",
                  "vars_plugins")


def test_path_is_stored_absolute(tmp_path):
    config = AnsibleConfig(str(tmp_path / "ansible.cfg"),
                           project_type="legacy")

    assert config.path == os.path.abspath(str(tmp_path / "ansible.cfg"))


def test_legacy_config_has_a_defaults_section(tmp_path):
    config = AnsibleConfig(str(tmp_path / "ansible.cfg"),
                           project_type="legacy")

    assert config.config.has_section("defaults")


def test_legacy_config_lists_collection_paths(tmp_path):
    config = AnsibleConfig(str(tmp_path / "ansible.cfg"),
                           project_type="legacy")

    collections_path = config.get_option("collections_path")

    assert "ansible/collections" in collections_path
    assert "collections" in collections_path


def test_legacy_config_lists_role_paths(tmp_path):
    config = AnsibleConfig(str(tmp_path / "ansible.cfg"),
                           project_type="legacy")

    roles_path = config.get_option("roles_path")

    assert "ansible/playbooks/roles" in roles_path


@pytest.mark.parametrize("option", PLUGIN_OPTIONS)
def test_legacy_config_includes_plugin_paths(tmp_path, option):
    config = AnsibleConfig(str(tmp_path / "ansible.cfg"),
                           project_type="legacy")

    assert config.get_option(option)


def test_modern_config_is_empty_until_merged(tmp_path):
    config = AnsibleConfig(str(tmp_path / "ansible.cfg"),
                           project_type="modern")

    assert config.config.sections() == []


def test_unknown_project_type_leaves_the_config_empty(tmp_path):
    config = AnsibleConfig(str(tmp_path / "ansible.cfg"))

    assert config.config.sections() == []


def test_merge_config_adds_a_section_and_stringifies_values(tmp_path):
    config = AnsibleConfig(str(tmp_path / "ansible.cfg"),
                           project_type="modern")

    config.merge_config({"defaults": {"forks": 20, "caching": "jsonfile"}})

    assert config.get_option("forks") == "20"
    assert config.get_option("caching") == "jsonfile"


def test_merge_config_updates_an_existing_section(tmp_path):
    config = AnsibleConfig(str(tmp_path / "ansible.cfg"),
                           project_type="legacy")

    config.merge_config({"defaults": {"forks": 20}})

    assert config.get_option("forks") == "20"


def test_merge_config_skips_an_empty_section(tmp_path):
    config = AnsibleConfig(str(tmp_path / "ansible.cfg"),
                           project_type="modern")

    config.merge_config({"empty": {}})

    assert not config.config.has_section("empty")


def test_load_config_reads_an_existing_file(tmp_path):
    path = tmp_path / "ansible.cfg"
    path.write_text("[defaults]\nforks = 20\n")
    config = AnsibleConfig(str(path), project_type="modern")

    config.load_config()

    assert config.get_option("forks") == "20"


def test_load_config_ignores_a_missing_file(tmp_path):
    config = AnsibleConfig(str(tmp_path / "ansible.cfg"),
                           project_type="modern")

    config.load_config()

    assert config.config.sections() == []


def test_write_config_writes_a_header_and_the_options(tmp_path):
    path = tmp_path / "ansible.cfg"
    config = AnsibleConfig(str(path), project_type="modern")
    config.merge_config({"defaults": {"forks": "20"}})

    config.write_config()

    content = path.read_text()
    assert "generated by DebOps" in content
    assert "forks = 20" in content


def test_get_option_reports_an_unknown_section(tmp_path):
    config = AnsibleConfig(str(tmp_path / "ansible.cfg"),
                           project_type="modern")

    with pytest.raises(configparser.NoSectionError):
        config.get_option("forks")
