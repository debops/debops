FREEZE_HEADER = """\
# Python packages installed in the project's Python virtual environment,
# managed by the 'debops project venv' command. Edit this file to add more
# packages, then run 'debops project venv install' to apply the changes.
# The packages listed in the DebOps seed can be upgraded to their latest
# versions with 'debops project venv upgrade'.

"""

COLLECTIONS_LOCK_HEADER = """\
# Ansible Collections installed in this project, pinned to the installed
# versions. This file is generated by 'debops project venv freeze'; to add or
# update collections, edit 'requirements.yml' and run 'debops project venv
# upgrade --collections' instead. The file can be used to reinstall the
# recorded state with:
#
#   ansible-galaxy collection install -r ansible/collections/requirements.lock.yml

"""


def check_scope(scope):
    """Check that the scope of a virtual environment action is valid."""
    if scope not in ('python', 'collections', 'all'):
        raise ValueError('The scope must be one of "python", '
                         '"collections" or "all", not '
                         '"{}"'.format(scope))


def _yaml_quote(value):
    """Quote a scalar for inclusion in a generated YAML file."""
    return str(value).replace("'", "''")


def seed_requirements():
    """Render the seed contents of the project 'requirements.txt' file.

    The seed lists the top-level Python packages which DebOps installs in the
    project virtual environment. It is written to the project at creation
    time and used again by the 'upgrade' command to learn which packages it
    is allowed to move to their latest versions.
    """
    template = jinja2.Template(
            pkgutil.get_data('debops',
                             os.path.join('_data',
                                          'templates',
                                          'projectdir',
                                          'modern',
                                          'requirements.txt.j2'))
            .decode('utf-8'), trim_blocks=True)
    return template.render()


def seed_names():
    """Return the names of the Python packages listed in the seed.

    Any version specifiers or extras are stripped, so that the result can be
    passed to 'pip install --upgrade' directly.
    """
    return [_normalize_name(name) for name in _package_lines(
            seed_requirements())]


def _normalize_name(name):
    """Normalize a Python package name for comparison.

    Package names are case-insensitive and treat '-', '_' and '.' as
    equivalent, per PEP 503.
    """
    return re.sub(r'[-_.]+', '-', name).lower()


def _package_lines(content):
    """Extract the package names from a requirements file content."""
    names = []
    for line in content.splitlines():
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        name = re.split(r'[<>=!~\[ ;]', line, maxsplit=1)[0].strip()
        if name:
            names.append(name)
    return names


# Seed packages which need non-Python, system-level build dependencies, and
# how to install those on the supported platforms. The checks are simple
# artifact lookups (compiler in $PATH, header files in the well-known include
# directories); DebOps does not try to detect system packages themselves.
EXTERNAL_DEPS = {
    'python-ldap': {
        'summary': 'a C compiler and the Python, LDAP and SASL development '
                   'files',
        'compiler': True,
        'python_headers': True,
        'headers': ['ldap.h', 'sasl/sasl.h'],
        'packages': {
            'debian': 'sudo apt install build-essential python3-dev '
                      'libldap2-dev libsasl2-dev',
            'fedora': 'sudo dnf install gcc python3-devel openldap-devel '
                      'cyrus-sasl-devel',
            'arch': 'sudo pacman -S base-devel python openldap cyrus-sasl',
            'alpine': 'apk add build-base python3-dev openldap-dev '
                      'cyrus-sasl-dev',
            'suse': 'sudo zypper install gcc python3-devel openldap2-devel '
                    'cyrus-sasl-devel',
            'macos': 'xcode-select --install; brew install openldap '
                     'cyrus-sasl (both are "keg-only", so their '
                     'CPPFLAGS/LDFLAGS need to be exported before '
                     'installation)',
        },
    },
}


def _os_family():
    """Return the OS family used to pick the package installation hints."""
    if platform.system() == 'Darwin':
        return 'macos'
    ids = [distro.id()] + distro.like().split()
    for family in ('debian', 'fedora', 'arch', 'alpine', 'suse'):
        if family in ids:
            return family
    return None


def _has_compiler():
    """Check if a C compiler is available in $PATH."""
    return any(shutil.which(compiler)
               for compiler in ('cc', 'gcc', 'clang'))


def _python_include_dir(interpreter):
    """Return the header directory of the given Python interpreter.

    The 'INCLUDEPY' configuration variable is inherited from the base
    installation even inside of a virtual environment, so this checks the
    location which a source build in the project environment would actually
    use - which may not be the Python running the DebOps command line.
    """
    command = [interpreter, '-c',
               'import sysconfig; '
               'print(sysconfig.get_config_var("INCLUDEPY") or "")']
    try:
        process = subprocess.Popen(command, stdout=subprocess.PIPE)
        out, _ = process.communicate()
    except OSError:
        return None
    if process.returncode != 0:
        return None
    return out.decode('utf-8').strip() or None


def _header_dirs():
    """Return the candidate directories for C header files.

    On macOS the Homebrew prefixes of both architectures are checked,
    including the "keg-only" formula directories, as well as the Xcode
    Command Line Tools SDK which holds the system headers.
    """
    dirs = ['/usr/include', '/usr/local/include']
    if platform.system() == 'Darwin':
        dirs.append('/opt/homebrew/include')
        for pattern in ('/opt/homebrew/opt/*/include',
                        '/usr/local/opt/*/include'):
            dirs.extend(sorted(glob.glob(pattern)))
        try:
            process = subprocess.Popen(['xcrun', '--show-sdk-path'],
                                       stdout=subprocess.PIPE,
                                       stderr=subprocess.DEVNULL)
            out, _ = process.communicate()
            sdk = out.decode('utf-8').strip()
            if process.returncode == 0 and sdk:
                dirs.append(os.path.join(sdk, 'usr', 'include'))
        except OSError:
            pass
    return dirs


def find_missing_external_deps(packages, interpreter='python3'):
    """Return a dict of packages whose external dependencies are missing.

    The keys are the normalized names of the packages which DebOps knows to
    need non-Python build dependencies that were not found, the values are
    their entries in var:`EXTERNAL_DEPS`.
    """
    candidates = [name for name in (_normalize_name(name) for name in packages)
                  if name in EXTERNAL_DEPS]
    missing = {}
    if not candidates:
        return missing

    compiler = _has_compiler()
    include_dir = _python_include_dir(interpreter)
    header_dirs = None

    for name in candidates:
        spec = EXTERNAL_DEPS[name]
        found = True
        if spec.get('compiler') and not compiler:
            found = False
        if found and spec.get('python_headers'):
            if not include_dir or not os.path.exists(
                    os.path.join(include_dir, 'Python.h')):
                found = False
        if found and spec.get('headers'):
            if header_dirs is None:
                header_dirs = _header_dirs()
            for header in spec['headers']:
                if not any(os.path.exists(os.path.join(directory, header))
                           for directory in header_dirs):
                    found = False
                    break
        if not found:
            missing[name] = spec
    return missing


def _format_missing_comment(name, spec):
    """Format the comment block which replaces a skipped package.

    The explanation goes above the commented-out package name, which is
    written without a space after the comment character so that it can be
    re-enabled with a single deletion.
    """
    command = spec['packages'].get(_os_family())
    if command:
        action = 'Install them with "{}"'.format(command)
    else:
        action = 'Install them with your system package manager'
    text = ('Skipped: {name} needs {summary}. {action}, then uncomment the '
            'package and run "debops project venv install".').format(
                name=name, summary=spec['summary'], action=action)
    return '\n'.join(textwrap.wrap(text, width=76, initial_indent='# ',
                                   subsequent_indent='# ')) + '\n#' + name


def comment_external_deps(content, missing):
    """Comment out the packages in var:`missing` in requirements content.

    The package lines are replaced with a comment block which explains what
    external dependencies are needed to install them. Commented packages stay
    inactive for the 'install' and 'upgrade' commands until the user enables
    them again.
    """
    lines = []
    for line in content.splitlines():
        stripped = line.strip()
        name = re.split(r'[<>=!~\[ ;]', stripped.split('#', 1)[0],
                        maxsplit=1)[0].strip() if stripped else ''
        if name and _normalize_name(name) in missing:
            lines.append(_format_missing_comment(
                name, missing[_normalize_name(name)]).rstrip('\n'))
        else:
            lines.append(line)
    return '\n'.join(lines) + ('\n' if content.endswith('\n') else '')


class ProjectVenv(object):
    """Manage the Python virtual environment of a DebOps project directory.

    The environment lives in the '.debops/venv/' subdirectory of a "modern"
    project and holds its own Ansible installation, so that the Ansible
    version and the controller-side Python dependencies are independent of
    the system packages. The exact package versions are recorded in the
    '.debops/requirements.txt' file which is meant to be committed to version
    control; the environment itself is not, and can be recreated on demand.
    """

    def __init__(self, project, *args, **kwargs):
        self.project = project
        self.project_path = project.path
        self.project_type = project.project_type
        self.args = args
        self.kwargs = kwargs

        if self.project_type != 'modern':
            raise ValueError('Python virtual environments can be managed '
                             'only in "modern" DebOps project directories')

        try:
            configured = (self.project.config.raw
                          .get('project', {}).get('venv', {}) or {})
        except AttributeError:
            configured = {}

        enabled = configured.get('enabled', False)
        if isinstance(enabled, str):
            enabled = bool(strtobool(enabled))
        if not enabled:
            raise ValueError('The Python virtual environment is not enabled '
                             'in this project; it can be enabled with the '
                             '"debops project venv enable" command')

        self.venv_path = os.path.join(
                self.project_path,
                os.path.expanduser(configured.get('path', '.debops/venv')))
        self.requirements_path = os.path.join(
                self.project_path,
                os.path.expanduser(configured.get('requirements',
                                                  '.debops/requirements.txt')))
        self.interpreter = configured.get('python', 'python3')

        self.collections_dir = os.path.join(self.project_path, 'ansible',
                                            'collections')
        self.collections_requirements = os.path.join(self.collections_dir,
                                                     'requirements.yml')
        self.collections_lock = os.path.join(self.collections_dir,
                                             'requirements.lock.yml')

    def exists(self):
        """Check if the virtual environment has been created."""
        return os.path.isfile(os.path.join(self.venv_path, 'bin', 'python'))

    def _subprocess_env(self):
        """Environment for the virtual environment subprocesses.

        PYTHONPATH is stripped so that an import path override meant for the
        DebOps command line itself, for example when it runs from a source
        checkout, does not leak into the virtual environment and its package
        metadata.
        """
        env = os.environ.copy()
        env.pop('PYTHONPATH', None)
        return env

    def _run(self, argv, **kwargs):
        """Run a command in the foreground and return its exit code."""
        logger.debug('Running command: ' + ' '.join(argv))
        process = subprocess.Popen(argv, env=self._subprocess_env(), **kwargs)
        process.communicate()
        return process.returncode

    def _galaxy_bin(self):
        """Return the path of the 'ansible-galaxy' binary from the virtual
        environment, or raise an error if it is not available."""
        galaxy = os.path.expanduser(
                self.project.config.raw['binaries']['ansible-galaxy'])
        if shutil.which(galaxy) is None:
            raise FileNotFoundError(
                    'The "' + galaxy + '" command is not available, so the '
                    'Ansible Collections cannot be managed; run '
                    '"debops project venv install" first')
        return galaxy

    def create(self):
        """Create the virtual environment if it does not exist yet."""
        if self.exists():
            logger.debug('Python virtual environment already exists in '
                         + unexpanduser(self.venv_path))
            return False

        logger.notice('Creating Python virtual environment in '
                      + unexpanduser(self.venv_path))
        rc = self._run([self.interpreter, '-m', 'venv', self.venv_path])
        if rc != 0:
            raise ChildProcessError(
                    'Cannot create the Python virtual environment in '
                    + unexpanduser(self.venv_path))

        python = os.path.join(self.venv_path, 'bin', 'python')
        rc = self._run([python, '-m', 'pip', 'install', '--upgrade', 'pip'])
        if rc != 0:
            raise ChildProcessError(
                    'Cannot upgrade pip in the Python virtual environment '
                    'in ' + unexpanduser(self.venv_path))
        return True

    def install(self, scope='all'):
        """Install the Python packages and Ansible Collections.

        The virtual environment is created first if needed. Python packages
        are installed from the project requirements file, after which the
        file is rewritten with the pinned versions of everything installed.
        Ansible Collections are installed from the lock file if it exists
        (which reproduces the locked versions), then from the requirements
        file, which applies new or changed entries on top.
        """
        check_scope(scope)
        if scope in ('python', 'all'):
            if not self.exists():
                self.create()
            if not os.path.isfile(self.requirements_path):
                logger.notice('Writing seed Python requirements to '
                              + unexpanduser(self.requirements_path))
                write_file(self.requirements_path,
                           comment_external_deps(
                               seed_requirements(),
                               find_missing_external_deps(
                                   seed_names(), self.interpreter))
                           + '\n')
            print('Installing Python packages from '
                  + unexpanduser(self.requirements_path) + ':', flush=True)
            python = os.path.join(self.venv_path, 'bin', 'python')
            rc = self._run([python, '-m', 'pip', 'install', '-r',
                            self.requirements_path])
            if rc != 0:
                raise ChildProcessError(
                        'Cannot install the Python requirements in '
                        + unexpanduser(self.venv_path))
        if scope in ('collections', 'all'):
            self.install_collections()
        self.freeze(scope)

    def _lock_names(self):
        """Return the normalized names of the packages recorded in the
        project requirements file."""
        if not os.path.isfile(self.requirements_path):
            return set()
        with open(self.requirements_path, encoding='utf-8') as fh:
            return {_normalize_name(name) for name in _package_lines(
                    fh.read())}

    def upgrade(self, scope='all'):
        """Upgrade the seed Python packages and Ansible Collections, and
        record the new versions in the requirements files.

        Only the Python packages listed both in the DebOps seed and in the
        project requirements file are upgraded, along with their
        dependencies. The requirements file decides what is managed:
        packages removed from it are not brought back, and packages added to
        it by the user stay at their pinned versions.

        Ansible Collections are force-installed from the requirements file,
        which upgrades the entries with loose version constraints to their
        latest versions.
        """
        check_scope(scope)
        if scope in ('python', 'all'):
            if not self.exists():
                raise FileNotFoundError(
                        'The Python virtual environment does not exist in '
                        + unexpanduser(self.venv_path)
                        + '; run "debops project venv install" first')
            names = [name for name in seed_names()
                     if name in self._lock_names()]
            if names:
                python = os.path.join(self.venv_path, 'bin', 'python')
                rc = self._run([python, '-m', 'pip', 'install', '--upgrade']
                               + names)
                if rc != 0:
                    raise ChildProcessError(
                            'Cannot upgrade the Python packages in '
                            + unexpanduser(self.venv_path))
        if scope in ('collections', 'all'):
            self.install_collections(upgrade=True)
        self.freeze(scope)

    def recreate(self, scope='all'):
        """Destroy the virtual environment or the installed Ansible
        Collections, and install them from scratch.

        The lock files are used for the reinstallation, so a recreation
        reproduces the locked versions.
        """
        check_scope(scope)
        if scope in ('python', 'all'):
            if os.path.isdir(self.venv_path):
                logger.notice('Removing Python virtual environment from '
                              + unexpanduser(self.venv_path))
                shutil.rmtree(self.venv_path)
        if scope in ('collections', 'all'):
            collections = os.path.join(self.collections_dir,
                                       'ansible_collections')
            if os.path.isdir(collections):
                logger.notice('Removing Ansible Collections from '
                              + unexpanduser(collections))
                shutil.rmtree(collections)
        self.install(scope=scope)

    def freeze(self, scope='all'):
        """Write the pinned versions of the installed Python packages and
        Ansible Collections to the project requirements files, and commit
        the changes when git auto-commit is enabled."""
        check_scope(scope)
        if scope in ('python', 'all'):
            self._freeze_python()
        if scope in ('collections', 'all'):
            self.freeze_collections()
        self.project.auto_commit()

    def _freeze_python(self):
        """Write the pinned versions of the installed packages to the
        project requirements file.

        Seed packages with external dependencies which are not installed
        (for example because their build dependencies are missing) are
        re-added as comment blocks, so that the explanation of what is
        needed to install them survives the freeze.
        """
        if not self.exists():
            raise FileNotFoundError(
                    'The Python virtual environment does not exist in '
                    + unexpanduser(self.venv_path)
                    + '; run "debops project venv install" first')
        python = os.path.join(self.venv_path, 'bin', 'python')
        process = subprocess.Popen([python, '-m', 'pip', 'freeze'],
                                   stdout=subprocess.PIPE,
                                   env=self._subprocess_env())
        out, _ = process.communicate()
        if process.returncode != 0:
            raise ChildProcessError(
                    'Cannot list the installed Python packages in '
                    + unexpanduser(self.venv_path))

        frozen = out.decode('utf-8')
        installed = {_normalize_name(name) for name in _package_lines(frozen)}
        blocks = [_format_missing_comment(name, EXTERNAL_DEPS[name]).rstrip('\n')
                  for name in seed_names()
                  if name in EXTERNAL_DEPS and name not in installed]

        content = FREEZE_HEADER + frozen
        if blocks:
            content += '\n' + '\n\n'.join(blocks) + '\n'
        print('Writing the pinned Python package versions to '
              + unexpanduser(self.requirements_path), flush=True)
        write_file(self.requirements_path, content, overwrite=True)

    def install_collections(self, upgrade=False):
        """Install the Ansible Collections required by the project.

        The exact versions recorded in the lock file are installed first, if
        it exists; then the requirements file is consulted without
        force-installing, so entries which are already installed and satisfy
        their constraints are skipped, and new or changed entries are
        applied on top. With var:`upgrade` the requirements file is
        force-installed, which upgrades the entries with loose version
        constraints to their latest versions.
        """
        galaxy = self._galaxy_bin()
        if not os.path.isfile(self.collections_requirements):
            raise FileNotFoundError(
                    'Cannot find the Ansible Collection requirements in '
                    + unexpanduser(self.collections_requirements))

        if not upgrade and os.path.isfile(self.collections_lock):
            print('Installing Ansible Collections from the lock file, '
                  + unexpanduser(self.collections_lock) + ':', flush=True)
            rc = self._run([galaxy, 'collection', 'install', '-r',
                            self.collections_lock])
            if rc != 0:
                raise ChildProcessError(
                        'Cannot install the Ansible Collections from '
                        + unexpanduser(self.collections_lock))

        verb = 'Force-upgrading' if upgrade else 'Installing'
        print(verb + ' Ansible Collections from '
              + unexpanduser(self.collections_requirements) + ':',
              flush=True)
        argv = [galaxy, 'collection', 'install', '-r',
                self.collections_requirements]
        if upgrade:
            argv.append('--force')
        rc = self._run(argv)
        if rc != 0:
            raise ChildProcessError(
                    'Cannot install the Ansible Collections from '
                    + unexpanduser(self.collections_requirements))

    def _collection_requirements(self):
        """Return the Ansible Collection requirements of the project, as a
        list of dicts; string entries are normalized to dicts."""
        with open(self.collections_requirements, encoding='utf-8') as fh:
            data = yaml.safe_load(fh) or {}
        entries = []
        for entry in (data.get('collections') or []):
            if isinstance(entry, str):
                entry = {'name': entry}
            entries.append(entry)
        return entries

    def _installed_collections(self):
        """Return the versions of the installed Ansible Collections, as a
        dict of collection name to version string.

        When a collection is present in more than one of the paths Ansible
        searches (for example both in the project directory and bundled with
        the 'ansible' Python package), the copy in the project directory
        wins, since it is the one Ansible will use.
        """
        galaxy = self._galaxy_bin()
        process = subprocess.Popen(
                [galaxy, 'collection', 'list', '--format', 'json'],
                stdout=subprocess.PIPE, env=self._subprocess_env())
        out, _ = process.communicate()
        if process.returncode != 0:
            raise ChildProcessError(
                    'Cannot list the installed Ansible Collections in '
                    + unexpanduser(self.project_path))

        project_root = os.path.realpath(os.path.join(
                self.collections_dir, 'ansible_collections'))
        installed = {}
        for path, collections in json.loads(out.decode('utf-8')).items():
            for name, metadata in collections.items():
                if (name not in installed
                        or os.path.realpath(path) == project_root):
                    installed[name] = metadata['version']
        return installed

    def freeze_collections(self):
        """Write the Ansible Collection lock file with the versions of the
        collections from the project requirements which are currently
        installed in the project.

        Entries with a source other than Ansible Galaxy (for example
        collections installed from a git repository) are preserved as they
        are written in the requirements file - their 'version' key refers to
        a git ref there, which cannot be pinned to a semantic version - with
        the currently installed version recorded in a comment above them
        when it can be determined.
        """
        entries = self._collection_requirements()
        if not entries:
            logger.notice('No Ansible Collection requirements found in '
                          + unexpanduser(self.collections_requirements))
            return
        installed = self._installed_collections()

        locked = []
        for entry in entries:
            name = entry.get('name')
            if not name:
                # Entries without a name (for example 'subdirs') cannot be
                # pinned; preserve them as they are
                locked.append((None, entry))
                continue

            fqcn = bool(re.match(r'^[a-zA-Z0-9_]+\.[a-zA-Z0-9_]+$', name))
            entry_type = entry.get('type') or ('galaxy' if fqcn else 'git')

            if entry_type == 'galaxy':
                if name not in installed:
                    logger.notice('The ' + name + ' collection is not '
                                  'installed, not included in the lock file')
                    continue
                entry = dict(entry, version=installed[name])
                locked.append((None, entry))
            else:
                comment = None
                if fqcn and name in installed:
                    comment = '# installed: ' + installed[name]
                locked.append((comment, entry))

        if not locked:
            logger.notice('No installed Ansible Collections found in '
                          + unexpanduser(self.collections_dir)
                          + ', not writing the lock file')
            return

        print('Writing the Ansible Collection lock file '
              + unexpanduser(self.collections_lock), flush=True)
        lines = [COLLECTIONS_LOCK_HEADER + 'collections:']
        for comment, entry in locked:
            lines.append('')
            if comment:
                lines.append('  ' + comment)
            items = list(entry.items())
            first_key, first_value = items[0]
            lines.append("  - {}: '{}'".format(first_key,
                                               _yaml_quote(first_value)))
            for key, value in items[1:]:
                if isinstance(value, list):
                    lines.append('    {}:'.format(key))
                    lines.extend("      - '{}'".format(_yaml_quote(item))
                                 for item in value)
                else:
                    lines.append("    {}: '{}'".format(key,
                                                       _yaml_quote(value)))

        write_file(self.collections_lock, '\n'.join(lines) + '\n',
                   overwrite=True)
