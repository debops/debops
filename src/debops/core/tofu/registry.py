"""The registry engine of the OpenTofu dependencies of a view.

The registry-addressed dependencies of a view are managed the same
way: the recorded set of the view's configuration drop-in drives a
generated file in the view's tree, which the reconcile keeps in step.
This module carries the shared machinery: the marker which separates
the generated files from the user's own, the reconcile of a managed
file, the write-once configuration drop-in and the diff which the
'--diff' option renders.
"""

import logging
import os

from .changes import file_change
import pkgutil
import re

import jinja2

from ..utils import write_file

logger = logging.getLogger(__name__)

# The path of the templates relative to the DebOps package data
TEMPLATE_ROOT = os.path.join('_data', 'templates', 'projectdir', 'modern',
                             'tofu')

# The shape of a bare TOML key: a key which matches it is emitted
# unquoted in the generated drop-ins
_TOML_BARE_KEY = re.compile(r'[A-Za-z0-9_-]+\Z')

# The marker in the generated files which separates the files DebOps
# owns from the files the user wrote: the reconcile touches only the
# files which carry it.
REGISTRY_MARKER = 'Generated by DebOps'


def render_template(name, **context):
    """Render one of the tofu view templates shipped with DebOps."""
    template = jinja2.Template(
        pkgutil.get_data('debops', os.path.join(TEMPLATE_ROOT, name))
        .decode('utf-8'), trim_blocks=True)
    return template.render(**context)


def view_tofu_root(project, view):
    """Return the root directory of a project's OpenTofu view."""
    if project.project_type == 'legacy':
        return os.path.join(project.path, 'tofu')
    return os.path.join(project.path, 'tofu', 'views', view)


def view_drop_in_path(project, view):
    """Return the path of the view's OpenTofu configuration drop-in."""
    filename_view = view.replace('/', '-')
    return os.path.join(project.path, '.debops', 'conf.d',
                        'view-' + filename_view + '-tofu.toml')


def write_view_drop_in(project, view, providers, modules=None,
                       binary_version=None):
    """Record the dependency set of a view in its configuration drop-in.

    The drop-in declares the 'views.<view>.tofu.providers' and
    'views.<view>.tofu.modules' options, which drive the generated
    'providers.tf' and 'modules.tf' files of the view, and the
    'views.<view>.tofu.binary_version' option, which pins the version
    of the OpenTofu binary the view runs with. The drop-in is
    written once, when the view is created: it is the user's file from
    then on, and the dependency set is changed by editing it. The
    configuration is reloaded from disk after the write, so that the
    same process reads the recorded sets at the rank a fresh process
    would read them -- the override sublayer, the hand-written files
    and the drop-in itself rank exactly as the disk says.

    Returns True when the drop-in was written, False when it already
    existed and was kept.
    """
    drop_in = view_drop_in_path(project, view)
    written = write_file(
        drop_in,
        render_template('view-tofu.toml.j2', view_name=view,
                        providers=providers or [],
                        modules=render_drop_in_modules(modules or {}),
                        binary_version=binary_version)
        + '\n',
        project=project.path)
    if not written:
        return False

    # A fresh process reads the drop-in through the ordinary
    # configuration loading: the override sublayer and the
    # hand-written files rank exactly as the disk says. The live
    # tree gets the same rank through the reload.
    project.reload()
    return True


def _toml_string(value):
    """Render a Python string as a TOML string literal.

    The escapes cover the characters which a basic TOML string cannot
    carry literally: the backslash, the quote and the control
    characters, which escape as their named escapes or as the
    '\\uXXXX' sequences.
    """
    escaped = []
    for char in value:
        if char == '\\':
            escaped.append('\\\\')
        elif char == '"':
            escaped.append('\\"')
        elif char == '\b':
            escaped.append('\\b')
        elif char == '\t':
            escaped.append('\\t')
        elif char == '\n':
            escaped.append('\\n')
        elif char == '\f':
            escaped.append('\\f')
        elif char == '\r':
            escaped.append('\\r')
        elif ord(char) < 0x20 or ord(char) == 0x7f:
            escaped.append('\\u{:04x}'.format(ord(char)))
        else:
            escaped.append(char)
    return '"' + ''.join(escaped) + '"'


def _toml_key(key):
    """Render a configuration table key as a TOML table key."""
    if _TOML_BARE_KEY.match(key):
        return key
    return _toml_string(key)


def _toml_value(value):
    """Render a configuration value as a TOML value.

    The Python literals render as their TOML equivalents: strings,
    numbers, booleans, lists as TOML arrays and tables as TOML inline
    tables. TOML has no null: the Python None is refused, and the
    values which a consumer cannot express through the configuration
    are carried through its own conventions.
    """
    if isinstance(value, str):
        return _toml_string(value)
    if value is True:
        return 'true'
    if value is False:
        return 'false'
    if value is None:
        raise ValueError('TOML has no null: the value cannot be '
                         'recorded in the configuration')
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if value != value or value in (float('inf'), float('-inf')):
            raise ValueError('The value {!r} is not a finite number '
                             'and has no TOML equivalent'.format(value))
        return repr(value)
    if isinstance(value, list):
        return '[ ' + ', '.join(_toml_value(item) for item in value) + ' ]'
    if isinstance(value, dict):
        if not value:
            return '{}'
        return '{ ' + ', '.join(
            '{} = {}'.format(_toml_key(key), _toml_value(val))
            for key, val in value.items()) + ' }'
    raise ValueError('The value {!r} of type {!r} has no TOML '
                     'equivalent'.format(value, type(value).__name__))


def render_drop_in_modules(modules):
    """Render the recorded module table of a drop-in.

    The table keys are the local module names; each entry carries the
    source address, the version pin and the inputs of the module
    instance, which the drop-in template renders as the TOML tables
    of the module.
    """
    return [{'name': name,
             'source': spec.get('source', ''),
             'version': spec.get('version', ''),
             'inputs_toml': '\n'.join(
                 '{} = {}'.format(_toml_key(key), _toml_value(value))
                 for key, value in (spec.get('inputs') or {}).items())}
            for name, spec in modules.items()]


def view_tofu_options(project, view):
    """The OpenTofu options of the view: the section of the view's
    configuration drop-in, an empty mapping when the view carries
    none. The drop-in is the user-owned authority for the recorded
    dependency sets; the readers consume this section rather than
    their own try/except chains."""
    try:
        return project.config.raw['views'][view]['tofu'] or {}
    except (KeyError, TypeError):
        return {}


def reconcile_managed_file(project, view, filename, expected, set_name,
                           entries_repr, force=False, dry_run=False):
    """Reconcile one generated file of a view.

    The file is DebOps-owned when it carries the 'Generated by
    DebOps' marker: the reconcile creates, updates or removes it to
    match the 'expected' content -- None when the recorded set is
    empty and the file should not exist. A file without the marker is
    user-owned: the reconcile refuses to touch it -- the recorded set
    is inert until the user removes their file or passes '--force' to
    hand the management back to DebOps.

    'set_name' names the recorded set in the log messages and the
    conflict refusal; 'entries_repr' renders the recorded set for
    them.

    Returns the list of proposed changes; with 'dry_run' nothing is
    written. Raises ValueError on the user-owned conflict without
    'force'.
    """
    path = os.path.join(view_tofu_root(project, view), filename)

    existing = None
    if os.path.exists(path):
        with open(path) as handle:
            existing = handle.read()
    generated = existing is not None and REGISTRY_MARKER in existing

    planned = None      # (action, new_content): the write the
    # reconcile proposes
    if expected is None:
        if existing is not None and generated:
            planned = ('remove', None)
    else:
        if existing is None:
            planned = ('create', expected)
        elif generated:
            if existing != expected:
                planned = ('update', expected)
        else:
            # A user-owned file: the reconcile refuses to touch it
            # unless '--force' hands the management back to DebOps
            if not force:
                raise ValueError(
                    "The '{}' file of the view {!r} in project {!r} "
                    'was not generated by DebOps. The recorded {} is '
                    'inert until the file is removed or '
                    "'--force' hands its management back to "
                    'DebOps.'.format(filename, view, project.name,
                                     set_name))
            if existing != expected:
                planned = ('update', expected)

    if planned is None:
        return []

    action, new_content = planned
    old_content = '' if action == 'create' else existing
    change = file_change(path, action, old_content, new_content,
                         project.path)

    if not dry_run:
        if action == 'remove':
            os.remove(path)
            logger.notice(
                'Removed the generated {} of the view {!r} in '
                'project {!r}: the recorded {} is empty'.format(
                    filename, view, project.name, set_name),
                extra={'allow': ['stderr', 'syslog']})
        else:
            write_file(path, new_content,
                       overwrite=True, project=project.path)
            logger.notice(
                '{} the generated {} of the view {!r} in project '
                '{!r}: the {} is now {}'.format(
                    'Created' if action == 'create' else 'Updated',
                    filename, view, project.name, set_name,
                    entries_repr),
                extra={'allow': ['stderr', 'syslog']})
    return [change]
